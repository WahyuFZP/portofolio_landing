export type PixelIconName = keyof typeof icons;

export default function PixelIcon({ name, className = "h-4 w-4" }: { name: PixelIconName; className?: string }) {
  return (
    <svg viewBox="0 0 8 8" shapeRendering="crispEdges" fill="currentColor" aria-hidden className={className}>
      {icons[name].flatMap((row, y) =>
        [...row].map((c, x) => (c === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} /> : null)),
      )}
    </svg>
  );
}
